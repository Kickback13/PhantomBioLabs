// Writes supabase/seed.sql from data/catalog.json. Safe to re-run: rows are upserted by slug.
// Usage: node scripts/generate-seed-sql.mjs [admin-email ...]
import { readFileSync, writeFileSync } from "node:fs";

const catalog = JSON.parse(readFileSync("data/catalog.json", "utf8"));
const adminEmails = process.argv.slice(2).map((e) => e.toLowerCase());

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const n = (v) => (v === null || v === undefined ? "null" : String(Number(v)));
const b = (v) => (v ? "true" : "false");
const arr = (a) => (a?.length ? `array[${a.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const json = (o) => `${q(JSON.stringify(o))}::jsonb`;

const lines = [];
lines.push("-- Generated by scripts/generate-seed-sql.mjs from data/catalog.json. Do not edit by hand.");
lines.push("begin;");

lines.push("insert into public.categories (slug, name, description, sort_order) values");
lines.push(catalog.categories.map((c) => `  (${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${n(c.sort_order)})`).join(",\n"));
lines.push("on conflict (slug) do update set name = excluded.name, description = excluded.description, sort_order = excluded.sort_order;");

lines.push("insert into public.products (slug, legacy_slug, legacy_woo_id, name, category_id, summary, description, specs, status, featured_rank, sort_order, review_flags)");
lines.push("select v.slug, v.legacy_slug, v.legacy_woo_id, v.name, c.id, v.summary, v.description, v.specs, v.status::public.product_status, v.featured_rank, v.sort_order, v.review_flags");
lines.push("from (values");
lines.push(
  catalog.products
    .map((p) => `  (${q(p.slug)}, ${q(p.legacy_slug)}, ${n(p.legacy_woo_id)}, ${q(p.name)}, ${q(p.category)}, ${q(p.summary)}, ${q(p.description)}, ${json(p.specs)}, ${q(p.status)}, ${n(p.featured_rank)}, ${n(p.sort_order)}, ${arr(p.review_flags)})`)
    .join(",\n"),
);
lines.push(") as v(slug, legacy_slug, legacy_woo_id, name, category, summary, description, specs, status, featured_rank, sort_order, review_flags)");
lines.push("join public.categories c on c.slug = v.category");
lines.push("on conflict (slug) do update set legacy_slug = excluded.legacy_slug, legacy_woo_id = excluded.legacy_woo_id, name = excluded.name, category_id = excluded.category_id, summary = excluded.summary, description = excluded.description, specs = excluded.specs, status = excluded.status, featured_rank = excluded.featured_rank, sort_order = excluded.sort_order, review_flags = excluded.review_flags;");

lines.push("insert into public.product_variants (product_id, label, sku, price_cents, compare_at_cents, in_stock, sort_order, legacy_woo_id)");
lines.push("select p.id, v.label, v.sku, v.price_cents, v.compare_at_cents, v.in_stock, v.sort_order, v.legacy_woo_id");
lines.push("from (values");
lines.push(
  catalog.products
    .flatMap((p) => p.variants.map((v) => `  (${q(p.slug)}, ${q(v.label)}, ${q(v.sku)}, ${n(v.price_cents)}, ${n(v.compare_at_cents)}::int, ${b(v.in_stock)}, ${n(v.sort_order)}, ${n(v.legacy_woo_id)}::int)`))
    .join(",\n"),
);
lines.push(") as v(product_slug, label, sku, price_cents, compare_at_cents, in_stock, sort_order, legacy_woo_id)");
lines.push("join public.products p on p.slug = v.product_slug");
lines.push("on conflict (product_id, label) do update set sku = excluded.sku, price_cents = excluded.price_cents, compare_at_cents = excluded.compare_at_cents, in_stock = excluded.in_stock, sort_order = excluded.sort_order, legacy_woo_id = excluded.legacy_woo_id;");

lines.push("insert into public.settings (key, value) values");
lines.push(Object.entries(catalog.settings).map(([k, v]) => `  (${q(k)}, ${json(v)})`).join(",\n"));
lines.push("on conflict (key) do update set value = excluded.value;");

if (adminEmails.length) {
  lines.push(`insert into public.admin_emails (email) values ${adminEmails.map((e) => `(${q(e)})`).join(", ")} on conflict do nothing;`);
  lines.push(`update public.profiles set is_admin = true where lower(email) in (${adminEmails.map(q).join(", ")});`);
}

lines.push("commit;");
writeFileSync("supabase/seed.sql", lines.join("\n") + "\n");
console.log(`wrote supabase/seed.sql (${catalog.categories.length} categories, ${catalog.products.length} products, ${catalog.products.reduce((s, p) => s + p.variants.length, 0)} sizes)`);
